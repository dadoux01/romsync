// Command gen extracts the save sizes of melonDS's ROM list into
// chipsizes.txt.
//
// Usage (from server/internal/chipdb):
//
//	curl -LO https://raw.githubusercontent.com/melonDS-emu/melonDS/<commit>/src/ROMList.cpp
//	go run ./gen -commit <commit> ROMList.cpp > chipsizes.txt
package main

import (
	"bufio"
	"encoding/binary"
	"flag"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
)

// melonDS's SaveMemType → save size (src/NDSCart/CartRetail.cpp, sramlengths).
// Type 0 means "no save" and is skipped.
var sramLengths = []int{0, 512, 8192, 65536, 128 << 10, 256 << 10, 512 << 10, 1 << 20, 8 << 20, 16 << 20, 64 << 20}

var entryRE = regexp.MustCompile(`\{0x([0-9A-Fa-f]{8}),\s*0x[0-9A-Fa-f]{8},\s*0x([0-9A-Fa-f]{8})\}`)

func main() {
	commit := flag.String("commit", "", "melonDS commit the file comes from")
	flag.Parse()
	if flag.NArg() != 1 || *commit == "" {
		fmt.Fprintln(os.Stderr, "usage: gen -commit <sha> ROMList.cpp")
		os.Exit(2)
	}
	f, err := os.Open(flag.Arg(0))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()

	sizes := map[string]int{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := entryRE.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		code32, _ := strconv.ParseUint(m[1], 16, 32)
		typ, _ := strconv.ParseUint(m[2], 16, 32)
		if typ == 0 || int(typ) >= len(sramLengths) {
			continue
		}
		// GameCodeAsU32 reads the 4 header bytes as a little-endian u32.
		var b [4]byte
		binary.LittleEndian.PutUint32(b[:], uint32(code32)) //nolint:gosec // parsed with bitSize 32
		code := string(b[:])
		sizes[code] = sramLengths[typ]
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	codes := make([]string, 0, len(sizes))
	for c := range sizes {
		codes = append(codes, c)
	}
	sort.Strings(codes)

	w := bufio.NewWriter(os.Stdout)
	defer w.Flush()
	fmt.Fprintf(w, "# Save sizes of Nintendo DS games, by game code (bytes).\n")
	fmt.Fprintf(w, "# Generated by gen/main.go from melonDS src/ROMList.cpp, commit %s.\n", *commit)
	fmt.Fprintf(w, "# melonDS: Copyright 2016-2026 melonDS team, GPL-3.0-or-later\n")
	fmt.Fprintf(w, "# (https://github.com/melonDS-emu/melonDS). Do not edit by hand.\n")
	for _, c := range codes {
		fmt.Fprintf(w, "%s %d\n", c, sizes[c])
	}
}
